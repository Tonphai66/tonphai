# โปรแกรมสร้างแม่สูตรคูณตามช่วงที่ผู้ใช้กำหนด (ใช้ Nested Loop ร่วมกับ range)

# รับค่าตัวเลขแม่สูตรคูณเริ่มต้นจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร start
start = int(input("แม่สูตรคูณเริ่มต้น : "))

# รับค่าตัวเลขแม่สูตรคูณสุดท้ายจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร end
end = int(input("แม่สูตรคูณสุดท้าย : "))

# ลูปนอก (Outer Loop): วนลูปตามช่วงแม่สูตรคูณที่ผู้ใช้กำหนด ตั้งแต่ start จนถึง end (บวก 1 เพื่อให้รวมค่า end เข้าไปด้วย)
for number in range(start, end + 1):
    print("สูตรคูณแม่", number)  # แสดงข้อความหัวข้อแม่สูตรคูณของรอบปัจจุบัน
    print("---------------")  # แสดงเส้นคั่นเพื่อความสวยงาม

    # ลูปใน (Inner Loop): วนลูปทำงาน 12 รอบ (ตั้งแต่ 1 ถึง 12) เพื่อใช้เป็นตัวคูณในแต่ละแม่
    for i in range(1, 13):
        # แสดงผลการคูณ โดยนำแม่สูตรคูณปัจจุบัน (number) คูณกับตัวคูณ (i)
        print(number, "x", i, " = ", number * i)

    print("---------------")  # แสดงเส้นคั่นเมื่อพิมพ์สูตรคูณแม่ปัจจุบันจบหนึ่งแม่