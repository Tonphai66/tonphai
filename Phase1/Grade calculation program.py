# โปรแกรมตัดเกรด (Grading Program)

# ส่วนรับข้อมูล (Input)
score = int(input("ป้อนคะแนนสอบของคุณ:"))  # รับค่าคะแนนจากผู้ใช้ แล้วแปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int)
print("คะแนนของคุณ คือ ", score)  # แสดงคะแนนที่ผู้ใช้กรอกเข้ามาทางหน้าจอ
grade = None  # สร้างตัวแปร grade สำหรับเก็บผลการตัดเกรด และกำหนดค่าเริ่มต้นเป็น None (ยังไม่มีค่า)

# ส่วนประมวลผล (Process) - ตรวจสอบเงื่อนไขช่วงคะแนนเพื่อตัดเกรด
if score >= 80 and score <= 100:  # ถ้าคะแนนมากกว่าหรือเท่ากับ 80 และน้อยกว่าหรือเท่ากับ 100
    grade = "A"  # กำหนดเกรดเป็น "A"
elif score >= 70 and score <= 79:  # ถ้าคะแนนอยู่ระหว่าง 70 ถึง 79
    grade = "B"  # กำหนดเกรดเป็น "B"
elif score >= 0 and score <= 69:  # ถ้าคะแนนอยู่ระหว่าง 0 ถึง 69
    grade = "F"  # กำหนดเกรดเป็น "F"
else:  # กรณีที่คะแนนไม่อยู่ในช่วง 0-100 (เช่น น้อยกว่า 0 หรือมากกว่า 100)
    grade = "N (Invalid)"  # กำหนดสถานะเป็นคะแนนไม่ถูกต้อง

# ส่วนแสดงผลลัพธ์ (Output)
print("เกรดของคุณ คือ ", grade)  # แสดงผลลัพธ์เกรดที่คำนวณได้ออกทางหน้าจอ