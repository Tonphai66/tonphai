# รับค่าชื่อจากผู้ใช้ โดยแสดงข้อความ "กรุณาป้อนชื่อของคุณ:" และเก็บค่าไว้ในตัวแปร name (ชนิดข้อมูลเป็น string)
name = input("กรุณาป้อนชื่อของคุณ:")

# รับค่าปีเกิดเป็น พ.ศ. จากผู้ใช้ แปลงข้อมูลที่รับเข้ามาให้เป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร year
year = int(input("กรุณาป้อนปีเกิดของคุณ (พ.ศ.):"))

# แสดงข้อความต้อนรับและค่าชื่อที่ผู้ใช้กรอกเข้ามา
print("ชื่อของคุณ = ", name)

# แสดงปีเกิด พ.ศ. ที่ผู้ใช้กรอกเข้ามา
print("ปีเกิด = ", year)

# คำนวณหาอายุโดยนำปี พ.ศ. 2567 ลบด้วยปีเกิด (year) แล้วแสดงผลลัพธ์ออกมา
print("ปีนี้คุณมีอายุ = ", 2567 - year, " ปี")