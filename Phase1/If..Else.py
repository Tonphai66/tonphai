# ส่วนรับข้อมูล (Input)
score = int(input("กรุณาป้อนคะแนนสอบของคุณ:"))  # รับค่าคะแนนจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร score
print("คะแนนสอบของคุณ =", score)  # แสดงค่าคะแนนที่ผู้ใช้กรอกเข้ามาออกทางหน้าจอ

# ส่วนประมวลผลและตรวจสอบเงื่อนไข (Process & Condition)
if score < 0:  # ตรวจสอบว่าคะแนนน้อยกว่า 0 หรือไม่ (กรณีป้อนค่าติดลบซึ่งเป็นไปไม่ได้)
    print("คะแนนไม่ถูกต้อง")  # ถ้าเงื่อนไขเป็นจริง (คะแนนติดลบ) ให้แสดงข้อความแจ้งเตือน
elif score >= 50:  # ถ้าคะแนนไม่ได้ติดลบ ให้มาตรวจสอบต่อว่าคะแนนมากกว่าหรือเท่ากับ 50 หรือไม่
    print("A")  # ถ้าเงื่อนไขนี้เป็นจริง จะแสดงผลเกรด "A"
else:  # กรณีอื่นๆ ที่เหลือนอกจากเงื่อนไขข้างต้น (คือคะแนนอยู่ระหว่าง 0 ถึง 49)
    print("F")  # ถ้าตกลงมาที่บล็อกนี้ จะแสดงผลเกรด "F"