# ตัวดำเนินการระบุตัวตน (Identity Operators) เช่น is และ is not ใช้สำหรับตรวจสอบว่าตัวแปรชี้ไปยังวัตถุ (Object) ชิ้นเดียวกันในหน่วยความจำหรือไม่

colorsA = ["สีแดง", "สีเขียว", "สีน้ำเงิน"]  # สร้าง List ชิ้นที่ 1 ในหน่วยความจำ และให้ตัวแปร colorsA อ้างอิงถึง
colorsB = ["สีแดง", "สีเขียว", "สีน้ำเงิน"]  # สร้าง List ชิ้นที่ 2 ขึ้นมาใหม่แยกต่างหาก (แม้ข้อมูลข้างในจะเหมือนกัน) แล้วให้ colorsB อ้างอิงถึง
data = colorsA  # กำหนดให้ตัวแปร data ชี้ไปยังวัตถุ (Object) เดียวกันกับ colorsA

# ตรวจสอบว่า colorsA "ไม่ได้" ชี้ไปยังวัตถุชิ้นเดียวกับ data หรือไม่
print(colorsA is not data)  # ได้ผลลัพธ์เป็น False (เพราะทั้งสองตัวแปรอ้างอิงไปยัง object ชิ้นเดียวกันในหน่วยความจำ)

# ตรวจสอบว่า colorsA "ไม่ได้" ชี้ไปยังวัตถุชิ้นเดียวกับ colorsB หรือไม่
print(colorsA is not colorsB)  # ได้ผลลัพธ์เป็น True (เพราะเป็นคนละ object กันในหน่วยความจำ แม้จะมีค่าข้อมูลข้างในเหมือนกันก็ตาม)