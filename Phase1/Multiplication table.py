# โปรแกรมสร้างแม่สูตรคูณตามตัวเลขที่ผู้ใช้ป้อนเข้ามา

# รับค่าตัวเลขแม่สูตรคูณจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร number
number = int(input("ป้อนตัวเลขแม่สูตรคูณ:"))

# วนลูปทำงาน 12 รอบ โดยให้ตัวแปร i มีค่าตั้งแต่ 1 ถึง 12 (เพื่อใช้เป็นตัวคูณตั้งแต่ 1 ถึง 12)
for i in range(1, 13):
    # แสดงผลการคูณในแต่ละรอบ โดยนำค่าแม่สูตรคูณ (number) มาแสดงคู่กับค่า i และผลลัพธ์จากการคูณ (number * i)
    print(number, "x", i, " = ", number * i)