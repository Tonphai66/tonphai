# ข้อมูลนักเรียนและการกำหนดค่าตัวแปร (Variables & Assignment)

# ประกาศและกำหนดค่าตัวแปรพร้อมกันหลายตัวในบรรทัดเดียว: name (ชื่อ), age (อายุ), grade (เกรดเฉลี่ย), และ status (สถานะ)
name, age, grade, status = "ก้องรักสยาม", 10, 3.99, True

# แก้ไขค่าข้อมูลของตัวแปร grade จากเดิม 3.99 ให้เป็น 4.0 (ค่าของตัวแปรใน Python สามารถเปลี่ยนแปลงแก้ไขได้ตลอดการทำงาน)
grade = 4.0

# ส่วนแสดงข้อมูลออกทางหน้าจอ (Output)
print("ชื่อนักเรียน = ", name)  # แสดงชื่อนักเรียนจากตัวแปร name
print("อายุ = ", age, "ขวบ")  # แสดงอายุจากตัวแปร age พร้อมข้อความต่อท้าย
print("เกรดเฉลี่ย = ", grade)  # แสดงเกรดเฉลี่ยล่าสุดจากตัวแปร grade (ที่ถูกแก้ไขแล้ว)
print("สถานะ = ", status)  # แสดงสถานะจากตัวแปร status (ชนิดข้อมูล Boolean: True)

# ส่วนตรวจสอบและแสดงชนิดข้อมูล (Data Types) ของตัวแปรต่างๆ ด้วยฟังก์ชัน type()
print(type(name))  # ตรวจสอบและแสดงชนิดข้อมูลของ name -> ผลลัพธ์ <class 'str'> (สตริง / ข้อความ)
print(type(age))  # ตรวจสอบและแสดงชนิดข้อมูลของ age -> ผลลัพธ์ <class 'int'> (จำนวนเต็ม)
print(type(grade))  # ตรวจสอบและแสดงชนิดข้อมูลของ grade -> ผลลัพธ์ <class 'float'> (เลขทศนิยม)
print(type(status))  # ตรวจสอบและแสดงชนิดข้อมูลของ status -> ผลลัพธ์ <class 'bool'> (บูลีน / ค่าความจริง True/False)
print(
    type(3.99)
)  # ตรวจสอบและแสดงชนิดข้อมูลของค่าคงที่ 3.99 โดยตรง -> ผลลัพธ์ <class 'float'>