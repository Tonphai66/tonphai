# การใช้งานคำสั่งวนซ้ำ while loop ใน Python ซึ่งจะทำงานวนซ้ำไปเรื่อยๆ ตราบใดที่เงื่อนไขยังคงเป็นจริง (True)

counter = 5  # กำหนดค่าเริ่มต้นให้ตัวแปร counter มีค่าเท่ากับ 5

while (
    counter < 10
):  # เงื่อนไขการวนลูป: ตรวจสอบว่า counter ยังน้อยกว่า 10 หรือไม่ ถ้าจริงจะทำงานในบล็อกด้านใน
    counter += 1  # เพิ่มค่าตัวแปร counter ทีละ 1 ในทุกๆ รอบ (เทียบเท่ากับ counter = counter + 1)
    print(counter)  # แสดงค่าปัจจุบันของตัวแปร counter ออกทางหน้าจอในแต่ละรอบ

print(
    "จบการทำงาน"
)  # แสดงข้อความนี้เมื่อค่าของ counter ไม่น้อยกว่า 10 แล้ว (เงื่อนไขเป็นเท็จ) ทำให้หลุดออกจากลูปมาทำงานบรรทัดนี้