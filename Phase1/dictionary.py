# การใช้งาน Dictionary (ดิกชันนารี) ใน Python ซึ่งเก็บข้อมูลในรูปแบบคู่ของ Key (คีย์) และ Value (ค่า)

# สร้าง Dictionary ชื่อ colors เก็บข้อมูลคำศัพท์สี โดย Key เป็นข้อความภาษาอังกฤษ และ Value เป็นภาษาไทย
colors = {"red": "แดง", "green": "เขียว", "blue": "น้ำเงิน"}

# สร้าง Dictionary ชื่อ confirm โดยใช้ค่า Boolean (True/False) เป็น Key และข้อความสถานะเป็น Value
confirm = {True: "ตกลง", False: "ยกเลิก"}

# สร้าง Dictionary ชื่อ month โดยใช้ตัวเลข (Integer) เป็น Key และชื่อเดือนเป็น Value
month = {1: "มกราคม", 2: "กุมภาพันธ์", 3: "มีนาคม"}

# สร้าง Dictionary ชื่อ numbers โดยใช้ข้อความเป็น Key และเก็บข้อมูลข้างในเป็น List (รายการตัวเลข)
numbers = {"เลขคู่": [2, 4, 6, 8, 10], "เลขคี่": [1, 3, 5, 7, 9]}

# เข้าถึงข้อมูลใน Dictionary ชื่อ numbers โดยระบุ Key เป็น "เลขคี่" เพื่อดึงค่าที่เป็น List ออกมาแสดงผลทางหน้าจอ
print(numbers["เลขคี่"])  # ผลลัพธ์ที่จะแสดงคือ [1, 3, 5, 7, 9]