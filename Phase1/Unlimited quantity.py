# โปรแกรมหาผลรวมของตัวเลขไม่จำกัดจำนวน (วนรับค่าไปเรื่อยๆ จนกว่าจะป้อนเลข 0 หรือติดลบเพื่อหยุด)

total = 0  # สร้างตัวแปร total สำหรับเก็บผลรวม โดยกำหนดค่าเริ่มต้นเป็น 0

while True:  # สร้างลูปแบบไม่รู้จบ (Infinite Loop) เพื่อเปิดให้ผู้ใช้ป้อนตัวเลขได้เรื่อยๆ
    # รับค่าตัวเลขจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร number
    number = int(input("ป้อนตัวเลข:"))

    if (
        number <= 0
    ):  # ตรวจสอบเงื่อนไขว่าถ้าผู้ใช้ป้อนตัวเลขน้อยกว่าหรือเท่ากับ 0 (ใช้เป็นสัญญาณหยุด)
        break  # ถ้าเงื่อนไขเป็นจริง ให้สั่งออกจากลูปทันที

    total += (
        number  # นำตัวเลขที่รับเข้ามาบวกสะสมเข้าไปในตัวแปร total (total = total + number)
    )

print(
    "ผลรวม = ", total
)  # แสดงผลรวมของตัวเลขทั้งหมดที่ผู้ใช้ป้อนออกทางหน้าจอหลังจากออกจากลูปแล้ว