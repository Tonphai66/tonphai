# ตัวดำเนินการกำหนดค่า (Assignment Operators)
x, y = 10, 2  # กำหนดค่าเริ่มต้นให้ตัวแปร x มีค่าเป็น 10 และ y มีค่าเป็น 2

print("x = ", x)  # แสดงค่าเริ่มต้นของตัวแปร x
print("y = ", y)  # แสดงค่าเริ่มต้นของตัวแปร y

x %= y  # ตัวดำเนินการ Modulus Assignment (เทียบเท่ากับ x = x % y)
# นำ 10 มาหารด้วย 2 จะได้ลงตัวพอดี ทำให้เหลือเศษ (Remainder) เป็น 0 แล้วเก็บค่า 0 ไว้ที่ x
print("ผลลัพธ์ = ", x)  # แสดงผลลัพธ์ค่าของ x หลังจากคำนวณ (ได้ 0)