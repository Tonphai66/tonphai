# การใช้งาน Ternary Operator (Conditional Expressions) หรือตัวดำเนินการเงื่อนไขแบบบรรทัดเดียวใน Python

# รับค่าตัวเลขจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร number
number = int(input("กรุณาป้อนตัวเลขของคุณ:"))

# แสดงค่าตัวเลขที่ผู้ใช้กรอกเข้ามาทางหน้าจอ
print("ตัวเลขของคุณ คือ ", number)

# ใช้ Ternary Operator ตรวจสอบเงื่อนไขในบรรทัดเดียว
# รูปแบบโครงสร้างคือ: [คำสั่งหรือค่าเมื่อเงื่อนไขเป็นจริง] if [เงื่อนไข] else [คำสั่งหรือค่าเมื่อเงื่อนไขเป็นเท็จ]
# ในที่นี้คือ: ถ้า number หารด้วย 2 ลงตัว (เศษเป็น 0) ให้ทำงานพิมพ์ "เลขคู่" แต่ถ้าไม่ลงตัว (เป็นเท็จ) ให้ทำงานพิมพ์ "เลขคี่"
print("เลขคู่") if number % 2 == 0 else print("เลขคี่")