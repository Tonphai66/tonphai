# รับค่าชื่อจากผู้ใช้ โดยแสดงข้อความและเก็บข้อมูลที่รับเข้ามาไว้ในตัวแปร name (ชนิดข้อมูลเริ่มต้นเป็น String)
name = input("กรุณาป้อนชื่อของคุณ:")

# รับค่าปีเกิดเป็น พ.ศ. จากผู้ใช้ แปลงข้อมูลให้เป็นตัวเลขจำนวนเต็ม (int) แล้วเก็บไว้ในตัวแปร year
year = int(input("กรุณาป้อนปีเกิดของคุณ (พ.ศ.):"))

# แสดงข้อความร่วมกับค่าของตัวแปร name ออกทางหน้าจอ
print("ชื่อของคุณ = ", name)

# แสดงข้อความร่วมกับค่าของตัวแปร year ออกทางหน้าจอ
print("ปีเกิด = ", year)

# คำนวณหาอายุโดยนำปี พ.ศ. 2567 ลบด้วยปีเกิด (year) แล้วแสดงผลลัพธ์อายุออกมา
print("ปีนี้คุณมีอายุ = ", 2567 - year)

# ตรวจสอบและแสดงชนิดข้อมูล (Data Type) ของตัวแปร name (ผลลัพธ์จะแสดงเป็น <class 'str'>)
print(type(name))

# ตรวจสอบและแสดงชนิดข้อมูล (Data Type) ของตัวแปร year หลังจากแปลงค่าแล้ว (ผลลัพธ์จะแสดงเป็น <class 'int'>)
print(type(year))
