# ตัวดำเนินการเปรียบเทียบ (Comparison Operators) ใช้สำหรับเปรียบเทียบค่าข้อมูล โดยผลลัพธ์ที่ได้จะเป็น Boolean (True หรือ False)
x, y = 100, 50  # กำหนดค่าเริ่มต้นให้ตัวแปร x เป็น 100 และ y เป็น 50

print(x == y)  # ตรวจสอบว่า x เท่ากับ y หรือไม่ -> ได้ผลลัพธ์เป็น False (เพราะ 100 ไม่เท่ากับ 50)
print(x != y)  # ตรวจสอบว่า x ไม่เท่ากับ y หรือไม่ -> ได้ผลลัพธ์เป็น True (เพราะ 100 ไม่เท่ากับ 50 จริง)
print(x > y)   # ตรวจสอบว่า x มากกว่า y หรือไม่ -> ได้ผลลัพธ์เป็น True (เพราะ 100 มากกว่า 50)
print(x >= y)  # ตรวจสอบว่า x มากกว่าหรือเท่ากับ y หรือไม่ -> ได้ผลลัพธ์เป็น True (เพราะ 100 มากกว่า 50)
print(x < y)   # ตรวจสอบว่า x น้อยกว่า y หรือไม่ -> ได้ผลลัพธ์เป็น False (เพราะ 100 ไม่ได้น้อยกว่า 50)
print(x <= y)  # ตรวจสอบว่า x น้อยกว่าหรือเท่ากับ y หรือไม่ -> ได้ผลลัพธ์เป็น False (เพราะ 100 ไม่ได้น้อยกว่าหรือเท่ากับ 50)