# ตัวดำเนินการทางตรรกศาสตร์ (Logical Operators) เช่น and, or, not ใช้สำหรับเชื่อมเงื่อนไขตั้งแต่สองเงื่อนไขขึ้นไป

username = input("ป้อนชื่อผู้ใช้:")  # รับค่าชื่อผู้ใช้จากผู้ใช้เก็บไว้ในตัวแปร username
password = input("ป้อนรหัสผ่าน:")  # รับค่ารหัสผ่านจากผู้ใช้เก็บไว้ในตัวแปร password

# ตรวจสอบเงื่อนไขด้วยตัวดำเนินการ or (อย่างน้อยหนึ่งเงื่อนไขเป็นจริง ผลลัพธ์จะเป็น True ทันที)
# ในที่นี้คือ ถ้า username เป็น "admin" หรือ password เป็น "1234" อย่างใดอย่างหนึ่งถูกต้อง จะถือว่าเงื่อนไขเป็นจริง
if username == "admin" or password == "1234":
    print("เข้าสู่ระบบสำเร็จ")  # แสดงข้อความนี้เมื่อเงื่อนไขด้านบนเป็นจริง (True)
else:
    print("ข้อมูลไม่ถูกต้อง")  # แสดงข้อความนี้เมื่อเงื่อนไขเป็นเท็จ (False) ทั้งหมด (คือผิดทั้ง username และ password)