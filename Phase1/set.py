# การใช้งาน Set (เซต) ใน Python ซึ่งเป็นโครงสร้างข้อมูลที่เก็บข้อมูลไม่ซ้ำกันและไม่มีลำดับ

# สร้าง Set ชื่อ animals สำหรับเก็บชุดข้อมูลของสัตว์ต่างๆ
animals = {"หมา", "แมว", "สิงโต", "เสือ", "ช้าง"}

# เพิ่มข้อมูลสมาชิกใหม่ "เป็ด" เข้าไปใน Set animals ด้วยเมธอด add()
animals.add("เป็ด")

# เพิ่มข้อมูลหลายๆ สมาชิก (รับค่าเป็น Tuple หรือ Iterable อื่นๆ) เข้าไปใน Set animals ด้วยเมธอด update()
animals.update(("หมู", "ยีราฟ"))

# สร้าง Set ชื่อ pets โดยใช้ฟังก์ชัน set() แปลงข้อมูล Tuple ให้กลายเป็น Set
pets = set(("หมา", "แมว", "กระต่าย", "เม่น"))

# แสดงข้อมูลทั้งหมดใน Set animals ออกทางหน้าจอ
print(animals)

# แสดงข้อมูลทั้งหมดใน Set pets ออกทางหน้าจอ
print(pets)

# หาข้อมูลที่เหมือนกันหรือซ้ำกัน (Intersection / อินเทอร์เซกต์) ระหว่าง Set animals กับ Set pets แล้วเก็บผลลัพธ์ไว้ในตัวแปร data
data = animals.intersection(pets)

# แสดงผลลัพธ์ข้อมูลที่ซ้ำกันของทั้งสอง Set ออกทางหน้าจอ (จะได้สมาชิกที่ปรากฏอยู่ทั้งใน animals และ pets เช่น "หมา" และ "แมว")
print(data)