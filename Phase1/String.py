# เจาะลึกการใช้งาน f-string (Formatted String Literals) ใน Python สำหรับจัดการและจัดรูปแบบสตริงได้อย่างสะดวก

year = 2540  # กำหนดตัวแปร year เก็บปีเกิด พ.ศ. 2540
salary = 25000  # กำหนดตัวแปร salary เก็บข้อมูลเงินเดือน 25000

# ใช้ f-string โดยใส่ตัวอักษร f ไว้หน้าข้อความ แล้วนำตัวแปร year มาใส่ในเครื่องหมายปีกกา {year} เพื่อแทรกค่าลงในสตริงทันที
message = f"เกิดเมื่อปี พ.ศ. {year}"

# ใช้ f-string คำนวณค่าทางคณิตศาสตร์ (2567 - year) และแทรกผลลัพธ์ลงในข้อความโดยตรงภายในเครื่องหมายปีกกา
age = f"ปีนี้คุณมีอายุ {2567 - year} ปี"

# ใช้ f-string จัดรูปแบบตัวเลข (Formatting) โดยระบุ :{salary:.2f} เพื่อให้แสดงผลตัวเลขเป็นทศนิยม 2 ตำแหน่งเสมอ
data = f"เงินเดือนของผม = {salary:.2f}"

print(data)  # แสดงผลลัพธ์ข้อความในตัวแปร data ออกทางหน้าจอ (จะได้ผลลัพธ์เป็น "เงินเดือนของผม = 25000.00")