# การใช้งานฟังก์ชันจัดการสตริงด้วยเมธอด .format() สำหรับแทรกค่าข้อมูลลงในตำแหน่งปีกกา ({}) ภายในข้อความ

# นำค่า "ก้อง" และ 30 ไปแทนที่ลงในเครื่องหมายปีกกาคู่ที่ 1 และคู่ที่ 2 ตามลำดับ แล้วเก็บผลลัพธ์ข้อความที่จัดรูปแบบแล้วไว้ในตัวแปร text
text = "ฉันชื่อ {} อายุ {} ปี".format("ก้อง", 30)

# แสดงผลข้อความในตัวแปร text ออกทางหน้าจอ (จะได้ผลลัพธ์เป็น "ฉันชื่อ ก้อง อายุ 30 ปี")
print(text)