# โปรแกรมหาผลรวมของตัวเลข 5 จำนวนที่รับค่าจากผู้ใช้

total = 0  # สร้างตัวแปร total สำหรับเก็บผลรวม โดยกำหนดค่าเริ่มต้นเป็น 0

for i in range(1, 6):  # วนลูปทำงาน 5 รอบ โดยให้ตัวแปร i มีค่าตั้งแต่ 1 ถึง 5 (แทนลำดับที่ 1 ถึง 5)
    # รับค่าตัวเลขจากผู้ใช้ แปลงข้อมูลเป็นตัวเลขจำนวนเต็ม (int) และเก็บไว้ในตัวแปร number
    # พร้อมแสดงข้อความบอกลำดับปัจจุบันโดยแปลง i เป็น string แล้วนำมาต่อกับข้อความ
    number = int(input("ลำดับที่ " + str(i) + " :"))

    total += number  # นำค่าตัวเลขที่รับเข้ามาบวกสะสมเพิ่มเข้าไปในตัวแปร total (เทียบเท่ากับ total = total + number)

print("ผลรวม = ", total)  # แสดงผลลัพธ์ค่าผลรวมทั้งหมดออกทางหน้าจอหลังจากวนลูปครบ 5 รอบแล้ว