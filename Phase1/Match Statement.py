# การใช้งานคำสั่ง match...case ใน Python (รองรับตั้งแต่ Python 3.10 ขึ้นไป) เพื่อตรวจสอบและเลือกการทำงานตามค่าของตัวแปร

service = input(
    "ป้อนหมายเลขบริการ(1-3):"
)  # รับค่าหมายเลขบริการจากผู้ใช้ และเก็บไว้ในตัวแปร service (ชนิดข้อมูลเป็น String)

match service:  # นำค่าในตัวแปร service มาตรวจสอบเทียบกับแต่ละเงื่อนไข (Case)
    case "1":  # ถ้าค่าที่รับเข้ามาตรงกับ "1"
        print("ถอนเงิน")  # แสดงข้อความ "ถอนเงิน" ออกทางหน้าจอ
    case "2":  # ถ้าค่าที่รับเข้ามาตรงกับ "2"
        print("ฝากเงิน")  # แสดงข้อความ "ฝากเงิน" ออกทางหน้าจอ
    case "3":  # ถ้าค่าที่รับเข้ามาตรงกับ "3"
        print(
            "สอบถามยอดเงินคงเหลือในบัญชี"
        )  # แสดงข้อความ "สอบถามยอดเงินคงเหลือในบัญชี" ออกทางหน้าจอ
    case "":  # ถ้าผู้ใช้กด Enter โดยไม่กรอกข้อมูลเลย (ค่าว่าง / String เปล่า)
        print(
            "หมายเลขบริการไม่ถูกต้อง"
        )  # แสดงข้อความแจ้งเตือนว่าหมายเลขบริการไม่ถูกต้อง