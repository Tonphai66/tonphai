# การใช้งาน Tuple (ทูเพิล) ใน Python ซึ่งเป็นโครงสร้างข้อมูลที่คล้ายกับ List แต่ข้อมูลข้างในจะไม่สามารถเปลี่ยนแปลง แก้ไข หรือลบได้ (Immutable)

# สร้าง Tuple ชื่อ colors สำหรับเก็บชุดข้อมูลของสี โดยมีข้อความ "แดง" ปรากฏซ้ำกันหลายตัว
colors = ("แดง", "เขียว", "น้ำเงิน", "ดำ", "ขาว", "แดง", "แดง")

# ใช้เมธอด .count() เพื่อค้นหาและนับจำนวนครั้งที่ข้อมูล "แดง" ปรากฏอยู่ใน Tuple ชื่อ colors
print(
    colors.count("แดง")
)  # แสดงผลลัพธ์จำนวนครั้งที่พบ (ในที่นี้ "แดง" ปรากฏอยู่ 3 ครั้ง ผลลัพธ์จึงแสดงเป็น 3)