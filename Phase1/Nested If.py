# การใช้งานคำสั่งเงื่อนไขซ้อนเงื่อนไข (Nested If) คือการนำคำสั่ง if ไปใส่ไว้ภายในบล็อก if อีกทีหนึ่ง

username = input("ป้อนชื่อผู้ใช้:")  # รับค่าชื่อผู้ใช้จากผู้ใช้เก็บไว้ในตัวแปร username
password = input("ป้อนรหัสผ่าน:")  # รับค่ารหัสผ่านจากผู้ใช้เก็บไว้ในตัวแปร password

if username == "member" and password == "1234":  # เงื่อนไขหลัก (Outer If): ตรวจสอบว่า username และ password ถูกต้องหรือไม่
    print("เข้าสู่ระบบสำเร็จ")  # แสดงข้อความเมื่อเข้าสู่ระบบผ่าน
    service = input("ป้อนหมายเลขบริการ(1-2):")  # รับค่าหมายเลขบริการเพิ่มเติมจากผู้ใช้
    
    if service == "1":  # เงื่อนไขย่อย (Nested If): ตรวจสอบว่าเลือกบริการหมายเลข 1 หรือไม่
        print("ถอนเงิน")  # แสดงข้อความเมื่อเลือกบริการถอนเงิน
    elif service == "2":  # ตรวจสอบว่าเลือกบริการหมายเลข 2 หรือไม่
        print("ฝากเงิน")  # แสดงข้อความเมื่อเลือกบริการฝากเงิน
    else:  # กรณีที่เลือกหมายเลขบริการนอกเหนือจาก 1 และ 2
        print("หมายเลขบริการไม่ถูกต้อง")  # แสดงข้อความแจ้งเตือนหมายเลขบริการไม่ถูกต้อง
else:  # กรณีที่เงื่อนไขหลักเป็นเท็จ (คือ username หรือ password ไม่ถูกต้องตั้งแต่แรก)
    print("ไม่พบบัญชีผู้ใช้")  # แสดงข้อความแจ้งเตือนว่าไม่พบบัญชีผู้ใช้