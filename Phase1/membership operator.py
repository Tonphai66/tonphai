# ตัวดำเนินการสมาชิก (Membership Operators) เช่น in และ not in ใช้สำหรับตรวจสอบว่ามีข้อมูลอยู่ในชุดข้อมูล (เช่น List, String, Tuple, Dictionary) หรือไม่

colors = [
    "สีแดง",
    "สีเขียว",
    "สีน้ำเงิน",
]  # สร้าง List ชื่อ colors สำหรับเก็บชุดข้อมูลของสี

# ตรวจสอบว่ามีข้อความ "สีแดง" อยู่ใน List colors หรือไม่ด้วยคำสั่ง in
print(
    "สีแดง" in colors
)  # ได้ผลลัพธ์เป็น True (เพราะมี "สีแดง" อยู่ใน List จริงๆ)

# ตรวจสอบว่าข้อความ "สีเหลือง" "ไม่มี" อยู่ใน List colors ใช่หรือไม่ ด้วยคำสั่ง not in
print(
    "สีเหลือง" not in colors
)  # ได้ผลลัพธ์เป็น True (เพราะ "สีเหลือง" ไม่ได้อยู่ใน List จริงๆ)