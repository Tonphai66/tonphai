# การใช้งานลูปซ้อนลูป (Nested Loop) คือการนำคำสั่ง loop ไปใส่ไว้ภายในบล็อก loop อีกทีหนึ่ง

for i in range(2):  # ลูปนอก (Outer Loop): วนลูปทำงาน 2 รอบ โดยตัวแปร i จะมีค่าเป็น 0 และ 1 ตามลำดับ
    print("รอบที่ ", i)  # แสดงข้อความบอกรอบการทำงานของลูปนอกในแต่ละรอบ
    for j in range(3):  # ลูปใน (Inner Loop): ในทุกๆ 1 รอบของลูปนอก ลูปในจะวนทำงานจนครบ 3 รอบ โดยตัวแปร j จะมีค่าเป็น 0, 1 และ 2
        print(j)  # แสดงค่าของตัวแปร j ออกทางหน้าจอในแต่ละรอบของลูปใน