# Exception (ตัวอย่างโค้ดที่ยังไม่ได้จัดการข้อผิดพลาด)

# รับค่าตัวเลขที่ 1 จากผู้ใช้งาน แล้วแปลงเป็นจำนวนเต็ม (int)
number1 = int(input("ป้อนตัวเลขที่ 1: "))

# รับค่าตัวเลขที่ 2 จากผู้ใช้งาน แล้วแปลงเป็นจำนวนเต็ม (int)
number2 = int(input("ป้อนตัวเลขที่ 2: "))

# นำตัวเลขทั้งสองมาหารกัน (หาก number2 เป็น 0 จะเกิด ZeroDivisionError ทันที)
result = number1 / number2

# แสดงผลลัพธ์การหารออกทางหน้าจอ
print("ผลลัพธ์ = ", result)