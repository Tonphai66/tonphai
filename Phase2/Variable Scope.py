# ขอบเขตตัวแปร (Variable Scope)
# balance เป็น Global Variable (ตัวแปรสาธารณะอยู่นอกฟังก์ชัน ทุกฟังก์ชันสามารถเข้าถึงได้)
balance = 1000 

# ฟังก์ชันสำหรับแสดงยอดเงินคงเหลือในบัญชี
def displayBalance():
    # ดึงค่าตัวแปร balance จากภายนอกมาแสดงผล
    print("ยอดเงินคงเหลือในบัญชี ", balance, " บาท")

# ฟังก์ชันสำหรับฝากเงิน (รับพารามิเตอร์ value)
def deposit(value):
    # ใช้คีย์เวิร์ด global เพื่อบอกว่าต้องการแก้ไขค่าตัวแปร balance ตัวหลักภายนอกฟังก์ชัน
    global balance
    
    # money เป็น Local Variable (ตัวแปรเฉพาะภายในฟังก์ชัน deposit นี้เท่านั้น)
    money = value 
    print("ฝากเงินจำนวน ", money, " บาท")
    
    # นำเงินที่ฝากมาบวกเพิ่มเข้ากับยอดเงินรวม
    balance += money

# ฟังก์ชันสำหรับถอนเงิน (รับพารามิเตอร์ value)
def withdraw(value):
    # ใช้คีย์เวิร์ด global เพื่ออนุญาตให้แก้ไขค่าตัวแปร balance ภายนอกได้
    global balance
    
    # amount เป็น Local Variable (ตัวแปรเฉพาะภายในฟังก์ชัน withdraw)
    amount = value
    print("ถอนเงินจำนวน ", amount, " บาท")
    
    # นำเงินที่ถอนไปหักลบออกจากยอดเงินรวม
    balance -= amount


# --- ส่วนของการเรียกใช้งานฟังก์ชัน (Function Calls) ---

# 1. แสดงยอดเงินเริ่มต้นในบัญชี (จะได้ 1000 บาท)
displayBalance()

