# กำหนดค่าตัวแปร data เป็น List ที่มีสมาชิก 3 ตัว คือ [1, 2, 3]
data = [1, 2, 3]

# ใช้คำสั่ง match-case (Pattern Matching) สำหรับตรวจสอบโครงสร้างข้อมูลแบบลำดับ (Sequence Pattern)
match data:
    # Sequence Pattern: ตรวจสอบว่าเป็น List เปล่าหรือไม่ (ไม่มีสมาชิกด้านในเลย)
    case []:
        print("ไม่มีข้อมูล")
        
    # Sequence Pattern: ตรวจสอบว่ามีสมาชิก 2 ตัวพอดีตามลำดับคือ 1 และ 2
    case [1, 2]:
        print("มีข้อมูล 2 รายการคือ 1 และ 2")
        
    # Sequence Pattern: ตรวจสอบว่ามีสมาชิก 3 ตัวพอดีตามลำดับคือ 1, 2 และ 3
    case [1, 2, 3]:
        print("มีข้อมูล 3 รายการคือ 1, 2 และ 3")