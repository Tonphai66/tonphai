# กำหนดค่าตัวแปร data เป็น "นาย" เพื่อจำลองคำนำหน้านาม
data = "นาย"

# ใช้คำสั่ง match-case (Pattern Matching) สำหรับตรวจสอบค่าในตัวแปร data
match data:
    # OR Pattern: ใช้เครื่องหมาย | (Pipe) เพื่อเชื่อมหลายทางเลือกเข้าด้วยกัน 
    # หากค่าใน data ตรงกับ "เด็กชาย" หรือ "นาย" อย่างใดอย่างหนึ่ง จะทำงานในบล็อกนี้
    case "เด็กชาย" | "นาย":
        print("เป็นเพศชาย")
        
    # OR Pattern: หากค่าใน data ตรงกับ "เด็กหญิง", "นางสาว" หรือ "นาง"
    case "เด็กหญิง" | "นางสาว" | "นาง":
        print("เป็นเพศหญิง")
        
    # Wildcard Pattern (Default Case): หากค่าไม่ตรงกับเคสด้านบนเลย
    case _:
        print("ไม่พบข้อมูล")