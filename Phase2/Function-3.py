# สร้าง Function โดยกำหนดค่าเริ่มต้น (Default Value) ให้กับพารามิเตอร์ salary เป็น 30000
def saveEmployee(name, department, salary=30000):
    # แสดงข้อมูลชื่อพนักงานและแผนก โดยดึงค่าจากตัวแปร name และ department
    print(f"ชื่อพนักงาน {name} , แผนก {department}")
    
    # แสดงข้อมูลเงินเดือน (หากไม่ได้ส่งค่ามา จะใช้ค่าเริ่มต้น 30000)
    print(f"เงินเดือน {salary} บาท")
    print("------------------------")


# เรียกใช้งานฟังก์ชัน โดยในตัวอย่างนี้ไม่ได้ส่งค่าเงินเดือนมา 
# ระบบจึงนำค่าเริ่มต้น (30000 บาท) ไปใช้งานโดยอัตโนมัติสำหรับพนักงานทุกคน
saveEmployee("ก้อง", "ไอที")
saveEmployee("นัด", "กราฟิก")
saveEmployee("โจ้", "การตลาด")
saveEmployee("เจน", "บัญชี")
