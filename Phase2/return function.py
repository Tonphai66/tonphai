# ประกาศฟังก์ชัน getPI เพื่อคืนค่าข้อมูลที่เป็นตัวเลขค่าพาย (3.14)
def getPI():
    return 3.14


# สูตรการคำนวณพื้นที่วงกลม: area = PI * radius ^ 2
# กำหนดตัวแปรเก็บค่ารัศมี (radius) เท่ากับ 5
radius = 5

# คำนวณพื้นที่วงกลม โดยเรียกใช้งานฟังก์ชัน getPI() มาคูณกับรัศมียกกำลังสอง (radius**2)
area = getPI() * radius**2

# แสดงผลลัพธ์พื้นที่วงกลมทางหน้าจอ
print("พื้นที่วงกลม = ", area, " ตารางเมตร")
