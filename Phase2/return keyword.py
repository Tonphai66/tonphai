# return keyword (การใช้ return เพื่อสั่งกระโดดออกจากฟังก์ชันเมื่อเกิดเงื่อนไขผิดพลาด)
balance = 1000  # ตัวแปร Global เก็บยอดเงินเริ่มต้นในบัญชี


# ฟังก์ชันสำหรับแสดงยอดเงินคงเหลือ
def displayBalance():
    print("ยอดเงินคงเหลือในบัญชี ", balance, " บาท")


# ฟังก์ชันสำหรับฝากเงิน (รับค่าพารามิเตอร์ value)
def deposit(value):
    global balance  # เรียกใช้ตัวแปร global เพื่อให้สามารถแก้ไขค่ายอดเงินข้างนอกได้
    money = value   # ตัวแปร Local เก็บจำนวนเงินที่ต้องการฝาก
    print("ฝากเงินจำนวน ", money, " บาท")
    
    # ตรวจสอบเงื่อนไข: ถ้าจำนวนเงินที่ฝากน้อยกว่าหรือเท่ากับ 0
    if money <= 0:
        print("ไม่สามารถฝากเงินได้")
        return  # ใช้ return เพื่อหยุดและกระโดดออกจากฟังก์ชันทันที (ไม่ให้ยอดเงินเพิ่มขึ้น)
        
    balance += money  # ถ้าผ่านเงื่อนไข จะนำเงินไปบวกเพิ่มเข้าบัญชี


# ฟังก์ชันสำหรับถอนเงิน (รับค่าพารามิเตอร์ value)
def withdraw(value):
    global balance  # เรียกใช้ตัวแปร global เพื่ออัปเดตยอดเงิน
    amount = value  # ตัวแปร Local เก็บจำนวนเงินที่ต้องการถอน
    print("ถอนเงินจำนวน ", amount, " บาท")
    
    # ตรวจสอบเงื่อนไข: ถอนเงินติดลบ/0 หรือถอนมากกว่ายอดเงินคงเหลือที่มี
    if amount <= 0 or amount > balance:
        print("ไม่สามารถถอนเงินได้")
        return  # ใช้ return เพื่อหยุดการทำงานทันที (ป้องกันยอดเงินติดลบ)
        
    balance -= amount  # ถ้าผ่านเงื่อนไข จะนำเงินไปหักออกจากยอดคงเหลือ


# --- ตัวอย่างการเรียกใช้งาน ---

# 1. แสดงยอดเงินเริ่มต้น (1,000 บาท)
displayBalance()

# 2. ทดลองถอนเงิน 1,001 บาท (เกินกว่าที่มี 1,000 บาท เงื่อนไขเป็นจริง จะพิมพ์ "ไม่สามารถถอนเงินได้" และ return ออกทันที)
withdraw(1001)

# 3. แสดงยอดเงินล่าสุดหลังทำรายการ (ยอดเงินยังคงเท่าเดิมคือ 1,000 บาท เพราะถูก return ดักไว้)
displayBalance()
