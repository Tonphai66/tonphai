# กำหนดค่าตัวแปร score เป็น 85 เพื่อจำลองคะแนนสอบของนักเรียน
score = 85

# ใช้คำสั่ง match-case (Pattern Matching) สำหรับตรวจสอบค่าในตัวแปร score
match score:
    # Literal Pattern: ถ้าค่าใน score เท่ากับ 100 เป๊ะๆ
    case 100:
        print("สอบได้คะแนนเต็ม")
        
    # Guard (Guard Pattern): ใช้คีย์เวิร์ด if ร่วมกับ case เพื่อสร้างเงื่อนไขกรองข้อมูลเพิ่มเติม
    # ในที่นี้คือตรวจสอบว่า score มีค่าตั้งแต่ 50 ขึ้นไป แต่ต้องน้อยกว่า 100 หรือไม่
    case score if 50 <= score < 100:
        print("ผ่านเกณฑ์การสอบวัดผล")
        
    # Wildcard Pattern (Default Case): ถ้าค่าคะแนนไม่ตรงกับเคสด้านบนเลย (เช่น ต่ำกว่า 50 หรือมากกว่า 100)
    case _:
        print("คะแนนไม่อยู่ในเกณฑ์ที่กำหนด")