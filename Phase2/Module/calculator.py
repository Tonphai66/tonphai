# calculator.py (โมดูลสำหรับเก็บฟังก์ชันคำนวณต่างๆ เพื่อนำไป import ใช้ในไฟล์อื่น)

# 1. ฟังก์ชันสำหรับการบวกเลขสองจำนวน
def add(x, y):
    return x + y  # คืนค่าผลบวกของ x และ y

# 2. ฟังก์ชันสำหรับการลบเลขสองจำนวน
def subtract(x, y):
    return x - y  # คืนค่าผลลบของ x และ y

# 3. ฟังก์ชันสำหรับการคูณเลขสองจำนวน
def multiply(x, y):
    return x * y  # คืนค่าผลคูณของ x และ y

# 4. ฟังก์ชันสำหรับการคำนวณเลขยกกำลัง
def power(x, y):
    return x ** y  # คืนค่า x ยกกำลัง y (x^y)