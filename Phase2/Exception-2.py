# Exception (การจัดการข้อผิดพลาดในโปรแกรม)

try:
    # ทดลองรันชุดคำสั่งที่มีความเสี่ยงจะเกิดข้อผิดพลาด
    number1 = int(input("ป้อนตัวเลขที่ 1: "))  # รับค่าตัวเลขที่ 1 และแปลงเป็นจำนวนเต็ม
    number2 = int(input("ป้อนตัวเลขที่ 2: "))  # รับค่าตัวเลขที่ 2 และแปลงเป็นจำนวนเต็ม
    result = number1 / number2                 # นำตัวเลขทั้งสองมาหารกัน
    print("ผลลัพธ์ = ", result)                 # แสดงผลลัพธ์หากไม่มีข้อผิดพลาด

except ValueError:
    # ดักจับข้อผิดพลาดกรณีที่ผู้ใช้งานกรอกตัวอักษรหรือข้อความที่ไม่สามารถแปลงเป็น int ได้
    print("ข้อมูลไม่ถูกต้อง กรุณาป้อนข้อมูลเฉพาะตัวเลขเท่านั้น!")

except ZeroDivisionError:
    # ดักจับข้อผิดพลาดกรณีที่ผู้ใช้งานป้อนตัวเลขที่ 2 เป็น 0 (เกิดการหารด้วยศูนย์)
    print("หารด้วยศูนย์ไม่ได้! เนื่องจากไม่ถูกนิยามในทางคณิตศาสตร์")

finally:
    # บล็อกนี้จะทำงาน "เสมอ" ทุกครั้ง ไม่ว่าจะเกิดข้อผิดพลาดขึ้นหรือไม่ก็ตาม
    print("---------------")
    print("End Program")
    print("---------------")