# lambda function 2x2x2
# สร้าง Lambda Function (ฟังก์ชันแบบไม่มีชื่อ) โดยรับพารามิเตอร์ 2 ตัว คือ base และ n
# จากนั้นคำนวณและส่งค่า base ยกกำลัง n กลับไป เก็บไว้ในตัวแปร result
result = lambda base, n: base**n

# เรียกใช้งานฟังก์ชัน result โดยส่งค่า base=2 และ n=4 (2 ยกกำลัง 4 ได้ 16) แล้วพิมพ์ผลลัพธ์
print("ผลลัพธ์ = ", result(2, 4))

# เรียกใช้งานฟังก์ชัน result โดยส่งค่า base=5 และ n=2 (5 ยกกำลัง 2 ได้ 25) แล้วพิมพ์ผลลัพธ์
print("ผลลัพธ์ = ", result(5, 2))
